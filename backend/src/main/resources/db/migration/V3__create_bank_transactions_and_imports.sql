-- =====================================================================================
-- V3: bank statement import feature (PhonePe CSV).
--
--   transaction_imports        one row per uploaded file (audit / history)
--   bank_transactions          the transactions themselves
--   transaction_import_errors  rejected CSV lines, used to build invalid_csv_statements.csv
-- =====================================================================================

CREATE TABLE transaction_imports (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    file_name       VARCHAR(255)  NOT NULL,
    status          VARCHAR(20)   NOT NULL CHECK (status IN ('PROCESSING', 'COMPLETED', 'FAILED')),
    total_rows      INTEGER       NOT NULL DEFAULT 0,
    imported_rows   INTEGER       NOT NULL DEFAULT 0,
    duplicate_rows  INTEGER       NOT NULL DEFAULT 0,
    invalid_rows    INTEGER       NOT NULL DEFAULT 0,
    error_message   VARCHAR(1000),
    started_at      TIMESTAMPTZ   NOT NULL,
    finished_at     TIMESTAMPTZ
);

CREATE INDEX idx_transaction_imports_started_at ON transaction_imports (started_at DESC);

CREATE TABLE bank_transactions (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Natural key from the statement. UNIQUE makes re-uploads idempotent:
    -- INSERT ... ON CONFLICT (transaction_id) DO NOTHING skips rows we already have.
    transaction_id  VARCHAR(64)    NOT NULL UNIQUE,
    transacted_at   TIMESTAMP      NOT NULL,          -- statement has no time zone (local IST time)
    details         VARCHAR(255)   NOT NULL,
    utr             VARCHAR(64),
    type            VARCHAR(10)    NOT NULL CHECK (type IN ('DEBIT', 'CREDIT')),
    instrument      VARCHAR(32),
    amount          NUMERIC(14, 2) NOT NULL CHECK (amount > 0),   -- NUMERIC, never float, for money
    import_id       BIGINT REFERENCES transaction_imports (id) ON DELETE SET NULL,
    created_at      TIMESTAMPTZ    NOT NULL DEFAULT now()
);

CREATE INDEX idx_bank_transactions_transacted_at ON bank_transactions (transacted_at DESC);
CREATE INDEX idx_bank_transactions_type          ON bank_transactions (type);

CREATE TABLE transaction_import_errors (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    import_id    BIGINT        NOT NULL REFERENCES transaction_imports (id) ON DELETE CASCADE,
    line_number  INTEGER       NOT NULL,
    raw_record   TEXT          NOT NULL,   -- the original CSV cells, re-encoded as one CSV line
    reason       VARCHAR(1000) NOT NULL
);

CREATE INDEX idx_transaction_import_errors_import ON transaction_import_errors (import_id, line_number);
